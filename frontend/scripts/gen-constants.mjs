#!/usr/bin/env node
/**
 * Generates src/engine/constants.ts and src/engine/vintage.ts.
 * Sources: local Python engine (no API/server/network) for named constants,
 * and the committed gold slice (../data/gold) for vintage-anchored data.
 * Both outputs are COMMITTED; src/engine/__tests__/constants.test.ts pins them.
 * Usage: node scripts/gen-constants.mjs (EVO_PYTHON overrides ../.venv/bin/python)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const GOLD = path.resolve(here, "../../data/gold");
const OUT = path.resolve(here, "../src/engine");
const root = path.resolve(here, "../..");
const python = process.env.EVO_PYTHON ?? path.join(root, ".venv/bin/python");
const exported = JSON.parse(execFileSync(python, ["-c",
  "import json; from engine.constants import CONSTANTS_TABLE, VINTAGE, ENGINE_VERSION; print(json.dumps({'constants': CONSTANTS_TABLE, 'vintage': VINTAGE, 'engine_version': ENGINE_VERSION}))"
], { cwd: root, encoding: "utf8" }));
const constants = exported;
const health = exported;
const SOURCE = "engine/constants.py";

// ---- constants.ts: one named export per scalar the engine chain uses ----
const CHAIN_NAMES = [
  "MULT", "RHO", "E_R", "E_EXT", "E_PM", "OKUN", "KAPPA", "GAMMA", "THETA",
  "PHI", "A_Z", "A_TAU", "A_LAM", "REFI", "TERM", "DIFF", "IPV_LR", "IPV_REV",
  "E_IPV_R", "E_IPV_G", "RJUV", "PM_DECAY", "CAL_SALARIO_MES",
];
const byName = Object.fromEntries(constants.constants.map((c) => [c.name, c]));
for (const n of CHAIN_NAMES) {
  if (!(n in byName)) throw new Error(`Python constants missing ${n}`);
}

const constantsTs = [
  "// GENERATED by scripts/gen-constants.mjs — do not edit. Regenerate with `npm run gen:constants`.",
  `// Source: ${SOURCE}, vintage ${constants.vintage}.`,
  ...CHAIN_NAMES.map((n) => `export const ${n} = ${byName[n].value};`),
  "",
  "export interface ConstantMeta { name: string; value: number; unit: string; provenance: string }",
  `export const CONSTANTS_META: ConstantMeta[] = ${JSON.stringify(constants.constants, null, 2)};`,
  "",
].join("\n");
writeFileSync(path.join(OUT, "constants.ts"), constantsTs);

// ---- vintage.ts: V0 / BASE_LEVERS / CENTRAL / OLDDEP from gold slice ----
const kpis = JSON.parse(readFileSync(path.join(GOLD, "kpis_perfiles.json"), "utf-8"));
const vintage = readFileSync(path.join(GOLD, "VINTAGE"), "utf-8").trim();

const kpi = (name) => {
  const v = Number(kpis.kpi[name].valor);
  if (!Number.isFinite(v)) throw new Error(`kpi ${name} is not numeric`);
  return v;
};

// mirrors engine/constants.py V0 exactly (24 keys)
const V0 = {
  u: kpi("paro_total"),
  pi: kpi("hicp_es"),
  g: kpi("pib_yoy"),
  bono: kpi("bono10y_es"),
  precio: kpi("precio_vivienda_mediano"),
  cuota: kpi("cuota_hipoteca_mediana"),
  salmes: byName.CAL_SALARIO_MES.value,
  salario: kpi("salario_medio"),
  ipv: kpi("vivienda_precio_yoy"),
  pens: kpi("gasto_pensiones_pib"),
  arop: kpi("arop_infantil"),
  edu: kpi("gasto_educacion_pib"),
  d1: kpi("salarios_publicos_pib"),
  p2: kpi("consumo_intermedio_pib"),
  d3: kpi("subvenciones_pib"),
  p51: kpi("inversion_publica_pib"),
  gtot: kpi("gasto_total_pib"),
  temp: kpi("temporalidad"),
  auton: kpi("autoempleo"),
  bls: kpi("bls_endurecimiento"),
  hip: kpi("hipotecas_anuales"),
  sobre: kpi("sobrecarga_vivienda"),
  ujuv: kpi("paro_juvenil"),
  vida: kpi("esperanza_vida"),
};

// mirrors engine/constants.py BASE_LEVERS exactly (10 keys)
const BASE_LEVERS = {
  r: kpi("euribor12m"),
  prima: kpi("spread_es_de"),
  sp: 0.0,
  lam: 0.9,
  pm: 0.0,
  tau: 0.0,
  z: 0.0,
  ext: 1.8,
  dem: 0.0,
  idx: 0.0,
};

const parseCsv = (name) => {
  const [head, ...rows] = readFileSync(path.join(GOLD, name), "utf-8").trim().split(/\r?\n/);
  const cols = head.split(",");
  return rows.map((r) => Object.fromEntries(r.split(",").map((v, i) => [cols[i], v])));
};

const CENTRAL = {};
for (const row of parseCsv("gold_escenarios_deuda.csv")) {
  if (row.escenario !== "central") continue;
  CENTRAL[Math.trunc(Number(row.year))] = {
    deuda: Number(row.deuda),
    pb: Number(row.pb),
    r_efectivo: Number(row.r_efectivo),
    g_nominal: Number(row.g_nominal),
    presion_demog: Number(row.presion_demog),
  };
}

const OLDDEP = {};
for (const row of parseCsv("gold_projections.csv")) {
  if (row.geo !== "ES" || row.variant !== "BSL") continue;
  OLDDEP[Math.trunc(Number(row.year))] = Number(row.olddep);
}

const vintageTs = [
  "// GENERATED by scripts/gen-constants.mjs — do not edit. Regenerate with `npm run gen:constants`.",
  `// Source: ../data/gold (vintage-anchored slice) and ${SOURCE}.`,
  `import type { Levers } from "./levers";`,
  "",
  `export const VINTAGE = ${JSON.stringify(vintage)};`,
  `export const ENGINE_VERSION = ${JSON.stringify(health.engine_version)};`,
  "",
  "export type V0Key = " +
    Object.keys(V0).map((k) => `"${k}"`).join(" | ") +
    ";",
  `export const V0: Record<V0Key, number> = ${JSON.stringify(V0, null, 2)};`,
  "",
  `export const BASE_LEVERS: Levers = ${JSON.stringify(BASE_LEVERS, null, 2)};`,
  "",
  "export interface CentralRow { deuda: number; pb: number; r_efectivo: number; g_nominal: number; presion_demog: number }",
  `export const CENTRAL: Record<number, CentralRow> = ${JSON.stringify(CENTRAL, null, 2)};`,
  "",
  `export const OLDDEP: Record<number, number> = ${JSON.stringify(OLDDEP, null, 2)};`,
  "",
].join("\n");
writeFileSync(path.join(OUT, "vintage.ts"), vintageTs);

if (vintage !== constants.vintage) {
  throw new Error(`VINTAGE file (${vintage}) != Python vintage (${constants.vintage}) — refuse generate mixed vintages`);
}

console.log(
  `Wrote constants.ts (${CHAIN_NAMES.length} named + ${constants.constants.length} meta rows) ` +
    `vintage.ts (vintage ${vintage})`,
);
